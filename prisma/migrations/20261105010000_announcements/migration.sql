CREATE TABLE `cms_announcements` (
  `id` CHAR(36) NOT NULL,
  `title` VARCHAR(200) NOT NULL,
  `description` TEXT NOT NULL,
  `display_mode` ENUM('MODAL', 'SPLASH') NOT NULL,
  `content_mode` ENUM('TEXT', 'IMAGE') NOT NULL,
  `image_media_id` VARCHAR(191) NULL,
  `image_alt` VARCHAR(500) NOT NULL DEFAULT '',
  `button_label` VARCHAR(80) NOT NULL DEFAULT '',
  `button_url` VARCHAR(2048) NOT NULL DEFAULT '',
  `open_in_new_tab` BOOLEAN NOT NULL DEFAULT false,
  `allow_suppression` BOOLEAN NOT NULL DEFAULT true,
  `repeat_after_days` SMALLINT UNSIGNED NOT NULL DEFAULT 30,
  `starts_at` DATETIME(3) NULL,
  `ends_at` DATETIME(3) NULL,
  `priority` INT UNSIGNED NOT NULL DEFAULT 0,
  `status` ENUM('DRAFT', 'PUBLISHED') NOT NULL DEFAULT 'DRAFT',
  `revision` INT UNSIGNED NOT NULL DEFAULT 1,
  `published_at` DATETIME(3) NULL,
  `deleted_at` DATETIME(3) NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  INDEX `cms_announcements_status_display_mode_starts_at_ends_at_idx` (`status`, `display_mode`, `starts_at`, `ends_at`),
  INDEX `cms_announcements_deleted_at_idx` (`deleted_at`),
  INDEX `cms_announcements_image_media_id_idx` (`image_media_id`),
  CONSTRAINT `cms_announcements_image_media_id_fkey` FOREIGN KEY (`image_media_id`) REFERENCES `cms_media_assets` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
